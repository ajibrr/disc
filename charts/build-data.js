/**
 * build-data.js
 * -------------
 * Converts the raw dashboard tick files in ../input/*_DASHBOARD.json into a
 * compact browser-ready bundle at ./data.js (window.CHART_DATA).
 *
 * The chart page loads data.js directly so it works from file:// too - no
 * local web server or fetch() required.
 *
 * Usage:  node build-data.js
 *
 * Drop additional *_DASHBOARD.json files (any date) into ../input and rerun
 * this script - new instruments/dates appear in the page dropdowns.
 */

const fs = require('fs');
const path = require('path');

const INPUT_DIR = path.join(__dirname, '..', 'input');
const OUT_FILE = path.join(__dirname, 'data.js');

/** Split a flat 1-second tick series into contiguous segments (no gaps). */
function segmentize(rows, priceKey) {
  const segments = [];
  let cur = null;
  let prevEpoch = null;
  let gaps = 0;

  for (const row of rows) {
    const p = row[priceKey];
    if (typeof p !== 'number' || !Number.isFinite(p)) continue;
    const t = Number(row.timestamp_epoch);
    if (!Number.isFinite(t)) continue;

    if (cur === null || t !== prevEpoch + 1) {
      cur = { start: t, prices: [] };
      segments.push(cur);
      if (prevEpoch !== null) gaps++;
    }
    cur.prices.push(Math.round(p * 100) / 100);
    prevEpoch = t;
  }
  return { segments, gaps };
}

const instruments = {};
let fileCount = 0;

for (const name of fs.readdirSync(INPUT_DIR)) {
  if (!name.endsWith('.json')) continue;
  const raw = JSON.parse(fs.readFileSync(path.join(INPUT_DIR, name), 'utf8'));

  const symbol = String(raw.asset || '').toUpperCase();
  if (!symbol || typeof raw !== 'object') {
    console.warn(`skip ${name}: no asset field`);
    continue;
  }

  const priceKey = symbol.toLowerCase();
  const tickKey = `${priceKey}_seconds`;
  const rows = raw[tickKey];
  if (!Array.isArray(rows) || rows.length === 0) {
    console.warn(`skip ${name}: no ${tickKey} array`);
    continue;
  }

  // Group ticks by calendar date (a single file may hold more than one day).
  const byDate = new Map();
  for (const row of rows) {
    const d = String(row.timestamp || '').slice(0, 10);
    if (!d) continue;
    if (!byDate.has(d)) byDate.set(d, []);
    byDate.get(d).push(row);
  }

  for (const [date, dayRows] of byDate) {
    const { segments, gaps } = segmentize(dayRows, priceKey);
    if (!segments.length) continue;

    const sessionStart = segments[0].start;
    const last = segments[segments.length - 1];
    const sessionEnd = last.start + last.prices.length - 1;

    if (!instruments[symbol]) {
      instruments[symbol] = {
        symbol,
        exchange: raw.exchange || '',
        expiry: raw.expiry || '',
        decimals: 2,
        dates: {},
      };
    }

    const firstTs = String(dayRows[0].timestamp || '');
    const lastTs = String(dayRows[dayRows.length - 1].timestamp || '');

    instruments[symbol].dates[date] = {
      date,
      sessionStart,
      sessionEnd,
      ticks: segments.reduce((n, s) => n + s.prices.length, 0),
      gaps,
      firstTick: firstTs.slice(11) || '',
      lastTick: lastTs.slice(11) || '',
      segments,
    };

    fileCount++;
    console.log(
      `${symbol.padEnd(7)} ${date}  ticks=${segments.reduce((n, s) => n + s.prices.length, 0)}  ` +
        `session=${firstTs.slice(11)}-${lastTs.slice(11)}  segments=${segments.length}  gaps=${gaps}`
    );
  }
}

const payload = {
  generatedAt: new Date().toISOString(),
  instruments,
};

fs.writeFileSync(
  OUT_FILE,
  '/* Auto-generated by build-data.js - do not edit by hand. */\n' +
    'window.CHART_DATA = ' +
    JSON.stringify(payload) +
    ';\n'
);

const kb = (fs.statSync(OUT_FILE).size / 1024).toFixed(0);
console.log(`\nwrote ${path.relative(process.cwd(), OUT_FILE)} (${kb} KB, ${Object.keys(instruments).length} instruments)`);
